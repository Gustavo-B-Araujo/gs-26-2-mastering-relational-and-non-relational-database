
CREATE TABLE IF NOT EXISTS StatusUsuario (
	cod NUMBER GENERATED AS IDENTITY PRIMARY KEY,
	enumerador VARCHAR2(9) NOT NULL UNIQUE,
	data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP
	);

CREATE TABLE IF NOT EXISTS TipoParentesco (
	cod NUMBER GENERATED AS IDENTITY PRIMARY KEY,
	enumerador VARCHAR2(20) NOT NULL UNIQUE,
	data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP
	);

CREATE TABLE IF NOT EXISTS TipoCurso (
	cod NUMBER GENERATED AS IDENTITY PRIMARY KEY,
	enumerador VARCHAR2(30) NOT NULL UNIQUE,
	data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP
	);

CREATE TABLE IF NOT EXISTS TipoNota (
	cod NUMBER GENERATED AS IDENTITY PRIMARY KEY,
	enumerador VARCHAR2(30) NOT NULL UNIQUE,
	data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP
	);

CREATE TABLE IF NOT EXISTS TipoPresenca (
	cod NUMBER GENERATED AS IDENTITY PRIMARY KEY,
	enumerador VARCHAR2(30) NOT NULL UNIQUE,
	data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP
	);

CREATE TABLE IF NOT EXISTS Pessoa (
	cod NUMBER GENERATED AS IDENTITY PRIMARY KEY,
	nome VARCHAR2(150) NOT NULL,
	num_documento VARCHAR2(11) NOT NULL UNIQUE,
	data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP
	);

CREATE TABLE IF NOT EXISTS Usuario (
	cod NUMBER GENERATED AS IDENTITY PRIMARY KEY,
	cod_status NUMBER NOT NULL REFERENCES StatusUsuario (cod),
	cod_pessoa NUMBER UNIQUE NOT NULL REFERENCES Pessoa (cod),
	senha_hash VARCHAR2(60) NOT NULL,
	data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP
	);

CREATE TABLE IF NOT EXISTS Diretor (
	cod NUMBER GENERATED AS IDENTITY PRIMARY KEY,
	cod_pessoa NUMBER NOT NULL UNIQUE REFERENCES Pessoa (cod),
	data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP
	);

CREATE TABLE IF NOT EXISTS Professor (
	cod NUMBER GENERATED AS IDENTITY PRIMARY KEY,
	cod_pessoa NUMBER NOT NULL UNIQUE REFERENCES Pessoa (cod),
	data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP
	);

CREATE TABLE IF NOT EXISTS Guardiao (
	cod NUMBER GENERATED AS IDENTITY PRIMARY KEY,
	cod_pessoa NUMBER NOT NULL UNIQUE REFERENCES Pessoa (cod),
	data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP
	);

CREATE TABLE IF NOT EXISTS Aluno (
	cod NUMBER GENERATED AS IDENTITY PRIMARY KEY,
	cod_pessoa NUMBER NOT NULL UNIQUE REFERENCES Pessoa (cod),
	data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP
	);

CREATE TABLE IF NOT EXISTS AlunoGuardiao (
	cod NUMBER GENERATED AS IDENTITY PRIMARY KEY,
	cod_guardiao NUMBER NOT NULL REFERENCES Guardiao (cod),
	cod_aluno NUMBER NOT NULL REFERENCES Aluno (cod),
	cod_tipo_parentesco NUMBER NOT NULL REFERENCES TipoParentesco (cod),
	data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP,
	CONSTRAINT uq_aluno_guardiao UNIQUE (cod_guardiao, cod_aluno)
	);

CREATE TABLE IF NOT EXISTS Escola (
	cod NUMBER GENERATED AS IDENTITY PRIMARY KEY,
	cod_diretor NUMBER NOT NULL REFERENCES Diretor (cod),
	nome VARCHAR2(100) NOT NULL UNIQUE,
	data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP
	);

CREATE TABLE IF NOT EXISTS Turma (
	cod NUMBER GENERATED AS IDENTITY PRIMARY KEY,
	cod_escola NUMBER NOT NULL REFERENCES Escola (cod),
	cod_tipo_curso NUMBER NOT NULL REFERENCES TipoCurso (cod),
	cod_professor NUMBER NOT NULL REFERENCES Professor (cod),
	semestre_referencia NUMBER NOT NULL CHECK (semestre_referencia IN (1, 2)),
	ano_referencia NUMBER NOT NULL CHECK (ano_referencia >= 2000),
	data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP
	);

CREATE TABLE IF NOT EXISTS TurmaAluno (
	cod NUMBER GENERATED AS IDENTITY PRIMARY KEY,
	cod_turma NUMBER NOT NULL REFERENCES Turma (cod),
	cod_aluno NUMBER NOT NULL REFERENCES Aluno (cod),
	data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP,
	CONSTRAINT uq_turma_aluno UNIQUE (cod_turma, cod_aluno)
	);

CREATE TABLE IF NOT EXISTS Avaliacao (
	cod NUMBER GENERATED AS IDENTITY PRIMARY KEY,
	cod_turma NUMBER NOT NULL REFERENCES Turma (cod),
	cod_tipo_nota NUMBER NOT NULL REFERENCES TipoNota (cod),
	nome VARCHAR2(50) NOT NULL,
	data_avaliacao DATE,
	data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP,
	CONSTRAINT uq_avaliacao UNIQUE (cod_turma, nome)
	);

CREATE TABLE IF NOT EXISTS Boletim (
	cod NUMBER GENERATED AS IDENTITY PRIMARY KEY,
	cod_turma_aluno NUMBER NOT NULL REFERENCES TurmaAluno (cod),
	cod_avaliacao NUMBER NOT NULL REFERENCES Avaliacao (cod),
	nota NUMBER(5,2) NOT NULL CHECK (nota BETWEEN 0 AND 100),
	data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP,
	CONSTRAINT uq_boletim UNIQUE (cod_turma_aluno, cod_avaliacao)
	);

CREATE TABLE IF NOT EXISTS ListaPresenca (
	cod NUMBER GENERATED AS IDENTITY PRIMARY KEY,
	cod_turma_aluno NUMBER NOT NULL REFERENCES TurmaAluno (cod),
	cod_tipo_presenca NUMBER NOT NULL REFERENCES TipoPresenca (cod),
	observacao VARCHAR2(150),
	data_presenca DATE NOT NULL CHECK(data_presenca >= DATE '2000-01-01'),
	data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP,
	CONSTRAINT uq_lista_presenca UNIQUE (cod_turma_aluno, data_presenca)
	);
